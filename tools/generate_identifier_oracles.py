#!/usr/bin/env python3
"""Freeze Character's identifier alphabets without adding a JDK8 CI runtime.

Run with --java8-home and --java21-home pointing at trusted JDK installations.
The default renderer uses the pinned JDK21/Unicode15 alphabet; native Java8
source certificates additionally require the Java8 alphabet. Reference data
comes from Character's int/code-point API, independently of Go's Unicode tables.
See JLS3.8 and Character.isJavaIdentifierStart/Part/isIdentifierIgnorable.
"""

import argparse
import gzip
import hashlib
from pathlib import Path
import subprocess
import tempfile


ORACLE = """import java.io.*;
class IdentifierAlphabetOracle {
 public static void main(String[] args) throws Exception {
  if (args.length != 0) {
   System.out.println(System.getProperty("java.specification.version"));
   return;
  }
  DataOutputStream out = new DataOutputStream(new BufferedOutputStream(System.out));
  for (int c = 0; c <= Character.MAX_CODE_POINT; c++) {
   out.writeByte((Character.isJavaIdentifierStart(c) ? 1 : 0)
     | (Character.isJavaIdentifierPart(c) ? 2 : 0)
     | (Character.isIdentifierIgnorable(c) ? 4 : 0));
  }
  out.close();
 }
}
"""


def stable(flags):
    return (flags & 1) | (2 if flags & 2 and not flags & 4 else 0)


def generate(java8, java21, destination, gofmt):
    with tempfile.TemporaryDirectory(prefix="java-identifier-oracle-") as temporary:
        directory = Path(temporary)
        source = directory / "IdentifierAlphabetOracle.java"
        source.write_text(ORACLE, encoding="utf-8")
        subprocess.run([str(java8 / "bin/javac"), "-proc:none", "-d", temporary, str(source)], check=True)
        snapshots = []
        for home, expected in [(java8, "1.8"), (java21, "21")]:
            command = [str(home / "bin/java"), "-XX:-UsePerfData", "-Xmx64m", "-cp", temporary, "IdentifierAlphabetOracle"]
            version = subprocess.check_output(command + ["version"], text=True).strip()
            if version != expected:
                raise ValueError(f"expected JDK {expected}, got {version}")
            raw = subprocess.check_output(command)
            if len(raw) != 0x110000 or any(flags & ~7 for flags in raw):
                raise ValueError("incomplete Character alphabet")
            snapshots.append(raw)

    old, modern = snapshots
    differences = []
    for codepoint, (old_flags, modern_flags) in enumerate(zip(old, modern)):
        old_bits = stable(old_flags)
        if old_bits == stable(modern_flags):
            continue
        if differences and differences[-1][1] + 1 == codepoint and differences[-1][2] == old_bits:
            differences[-1][1] = codepoint
        else:
            differences.append([codepoint, codepoint, old_bits])

    destination.mkdir(parents=True, exist_ok=True)
    fixture = destination / "testdata/java8_identifier_flags.bin.gz"
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_bytes(gzip.compress(old, mtime=0))
    (fixture.parent / "java21_identifier_flags.bin.gz").write_bytes(gzip.compress(modern, mtime=0))
    modern_ranges = []
    for codepoint, flags in enumerate(modern):
        bits = stable(flags)
        if not bits:
            continue
        if modern_ranges and modern_ranges[-1][1] + 1 == codepoint and modern_ranges[-1][2] == bits:
            modern_ranges[-1][1] = codepoint
        else:
            modern_ranges.append([codepoint, codepoint, bits])
    modern_output = [
        "// Code generated by tools/generate_identifier_oracles.py; DO NOT EDIT.",
        "// Frozen JDK21 Character alphabet; independent of the Go toolchain's Unicode version.",
        "// Raw oracle SHA256: " + hashlib.sha256(modern).hexdigest(),
        "package class_context", "", 'import "sort"', "",
        "var java21IdentifierRanges = [...]struct { first, last rune; bits uint8 }{",
    ]
    modern_output.extend(f"{{0x{first:X}, 0x{last:X}, {bits}}}," for first, last, bits in modern_ranges)
    modern_output += ["}", "", "func java21IdentifierBits(r rune) uint8 {",
                      "// The ASCII fast path follows the same profile, including currency/connector characters.",
                      "if r < 128 {",
                      "if r=='_' || r=='$' || r>='a'&&r<='z' || r>='A'&&r<='Z' { return 3 }",
                      "if r>='0'&&r<='9' { return 2 }", "return 0", "}",
                      "i := sort.Search(len(java21IdentifierRanges), func(i int) bool { return java21IdentifierRanges[i].last >= r })",
                      "if i < len(java21IdentifierRanges) && r >= java21IdentifierRanges[i].first { return java21IdentifierRanges[i].bits }",
                      "return 0", "}", ""]
    (destination / "java21_identifier_tables.go").write_text("\n".join(modern_output), encoding="utf-8")
    output = [
        "// Code generated by tools/generate_identifier_oracles.py; DO NOT EDIT.",
        "// Java8/Java21 Character int API over all 0x110000 code points.",
        "// Ignorable characters cannot preserve an exact source name: javac strips them.",
        "// Reference raw Java8 SHA256: " + hashlib.sha256(old).hexdigest(),
        "// Reference raw Java21 SHA256: " + hashlib.sha256(modern).hexdigest(),
        "package class_context", "", 'import "sort"', "",
        "var java8IdentifierOverrides = [...]struct { first, last rune; bits uint8 }{",
    ]
    output.extend(f"{{0x{first:X}, 0x{last:X}, {bits}}}," for first, last, bits in differences)
    output += ["}", "", "func java8IdentifierBits(r rune) uint8 {",
               "bits := java21IdentifierBits(r)",
               "// ASCII is identical in both Character profiles.",
               "if r < 128 { return bits }",
               "i := sort.Search(len(java8IdentifierOverrides), func(i int) bool { return java8IdentifierOverrides[i].last >= r })",
               "if i < len(java8IdentifierOverrides) && r >= java8IdentifierOverrides[i].first { return java8IdentifierOverrides[i].bits }",
               "return bits", "}", ""]
    (destination / "java8_identifier_tables.go").write_text("\n".join(output), encoding="utf-8")
    subprocess.run([gofmt, "-w", str(destination / "java21_identifier_tables.go"),
                    str(destination / "java8_identifier_tables.go")], check=True)
    print(f"generated {len(modern_ranges)} JDK21 ranges and {len(differences)} profile-difference ranges; frozen raw Java8 oracle SHA256 {hashlib.sha256(old).hexdigest()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--java8-home", type=Path, required=True)
    parser.add_argument("--java21-home", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "classparser/decompiler/core/class_context")
    parser.add_argument("--gofmt", default="gofmt", help="Go formatter for reproducible generated sources")
    arguments = parser.parse_args()
    generate(arguments.java8_home, arguments.java21_home, arguments.output, arguments.gofmt)
