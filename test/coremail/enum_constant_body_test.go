// J2B-021: javac --release 8 emits each constant body as Owner$N with
// InnerClasses and EnclosingMethod. An obfuscator can rename those classes
// and delete both attributes. The body is still expressible as a constant
// block; a standalone subclass of an enum is not legal source.
func TestRenamedEnumConstantBodyFoldsIntoConstant(t *testing.T) {
	javac, java := tool(t, "javac"), tool(t, "java")
	dir := t.TempDir()
	command(t, javac, "-proc:none", "--release", "8", "-g:none", "-d", dir, "testdata/enum/ConstantBody.java", "testdata/enum/ConstantBodyDriver.java")
	entries := renamedConstantBodies(t, dir)
	original := command(t, java, "-cp", dir, "fixtures.ConstantBodyDriver")
	if original != "ok" {
		t.Fatalf("renamed classes changed behavior: %q", original)
	}
	generated := decompileArchive(t, dir, entries, "fixtures/ConstantBody.class")
	if strings.Contains(generated, "decompile dump failed") || strings.Contains(generated, parser.DecompileStubMarker) {
		t.Fatalf("renamed constant body refused:\n%s", generated)
	}
	for _, piece := range []string{
		"LE {",
		"LT {",
		"PLAIN;",
		"public static final ConstantBody a = LE;",
		"public static final ConstantBody b = LT;",
		"(var1) <= (var2)",
		"(var1) < (var2)",
	} {
		if !strings.Contains(generated, piece) {
			t.Fatalf("missing %q:\n%s", piece, generated)
		}
	}
	if strings.Contains(generated, "BodyLE") || strings.Contains(generated, "BodyLT") {
		t.Fatalf("obfuscated body class leaked into source:\n%s", generated)
	}
	body := decompileArchive(t, dir, entries, "fixtures/BodyLE.class")
	if strings.Contains(body, "class BodyLE") || !strings.Contains(body, "regenerated by javac") {
		t.Fatalf("standalone body was not owned by the enum:\n%s", body)
	}
	rebuilt := filepath.Join(dir, "rebuilt")
	put(t, filepath.Join(rebuilt, "fixtures/ConstantBody.java"), []byte(generated))
	command(t, javac, "-proc:none", "--release", "8", "-d", rebuilt, filepath.Join(rebuilt, "fixtures/ConstantBody.java"))
	got := command(t, java, "-cp", rebuilt+string(os.PathListSeparator)+dir, "fixtures.ConstantBodyDriver")
	if got != original {
		t.Fatalf("original %q regenerated %q\n%s", original, got, generated)
	}
}

func TestRenamedEnumConstantBodyRejectsNonEnumSubclass(t *testing.T) {
	javac := tool(t, "javac")
	dir := t.TempDir()
	command(t, javac, "-proc:none", "--release", "8", "-g:none", "-d", dir, "testdata/enum/ConstantBody.java")
	entries := renamedConstantBodies(t, dir)
	obj, err := parser.Parse(entries["fixtures/BodyLE.class"])
	if err != nil {
		t.Fatal(err)
	}
	obj.AccessFlags &^= 0x4000
	entries["fixtures/BodyLE.class"] = obj.Bytes()
	src := decompileArchive(t, dir, entries, "fixtures/ConstantBody.class")
	if !strings.Contains(src, "constant-specific") {
		t.Fatalf("non-enum body was emitted:\n%s", src)
	}
}

func renamedConstantBodies(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	names := []string{"fixtures/ConstantBody.class", "fixtures/ConstantBody$1.class", "fixtures/ConstantBody$2.class"}
	objects := map[string]*parser.ClassObject{}
	for _, name := range names {
		obj, err := parser.Parse(readFile(t, filepath.Join(dir, name)))
		if err != nil {
			t.Fatal(err)
		}
		objects[name] = obj
	}
	rewrites := [][2]string{{"fixtures/ConstantBody$1", "fixtures/BodyLE"}, {"fixtures/ConstantBody$2", "fixtures/BodyLT"}}
	for _, obj := range objects {
		for _, pair := range rewrites {
			rewriteUTF8(obj, pair[0], pair[1])
		}
	}
	for _, name := range []string{"fixtures/ConstantBody$1.class", "fixtures/ConstantBody$2.class"} {
		stripEnumBodyIdentity(objects[name])
	}
	enumObj := objects["fixtures/ConstantBody.class"]
	renameEnumField(t, enumObj, "LE", "a")
	renameEnumField(t, enumObj, "LT", "b")
	renameEnumField(t, enumObj, "PLAIN", "c")
	renameEnumField(t, enumObj, "$VALUES", "k")
	entries := map[string][]byte{}
	renamed := map[string]string{
		"fixtures/ConstantBody.class":   "fixtures/ConstantBody.class",
		"fixtures/ConstantBody$1.class": "fixtures/BodyLE.class",
		"fixtures/ConstantBody$2.class": "fixtures/BodyLT.class",
	}
	for old, obj := range objects {
		raw := obj.Bytes()
		entries[renamed[old]] = raw
		put(t, filepath.Join(dir, renamed[old]), raw)
	}
	return entries
}

func rewriteUTF8(obj *parser.ClassObject, from, to string) {
	for _, info := range obj.ConstantPool {
		u, ok := info.(*parser.ConstantUtf8Info)
		if !ok || u == nil || !strings.Contains(u.Value, from) {
			continue
		}
		u.SetString(strings.ReplaceAll(u.Value, from, to))
	}
}

func stripEnumBodyIdentity(obj *parser.ClassObject) {
	kept := obj.Attributes[:0]
	for _, attribute := range obj.Attributes {
		switch attribute := attribute.(type) {
		case *parser.InnerClassesAttribute:
			continue
		case *parser.UnparsedAttribute:
			if attribute != nil && attribute.Name == "EnclosingMethod" {
				continue
			}
		}
		kept = append(kept, attribute)
	}
	obj.Attributes = kept
}

func decompileArchive(t *testing.T, dir string, entries map[string][]byte, name string) string {
	t.Helper()
	fs, err := parser.NewJarFSFromLocal(archive(t, dir, entries))
	if err != nil {
		t.Fatal(err)
	}
	defer fs.Close()
	src, err := fs.ReadFile(name)
	if err != nil {
		t.Fatal(err)
	}
	return string(src)
}
