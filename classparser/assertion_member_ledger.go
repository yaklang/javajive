package javaclassparser

import "reflect"

// The ordinary member inventory runs before final assertion publication. Its
// absent field/initializer entries can be discharged only by the same complete
// physical packet whose reads were all consumed by typed source assertions.
// This records reconstruction evidence; it grants no source transformation.
func (c *ClassObjectDumper) recordStandaloneAssertionMembers(source string) {
	if c == nil || c.obj == nil || c.report == nil || c.obj.AccessFlags&0x6000 != 0 {
		return
	}
	state := c.nativeStandaloneAssertion
	if state == nil || state.packet == nil || c.nativeAssertionProtocol() != state.packet || !c.nativeStandaloneAssertionClosed(source) {
		return
	}
	// Reopen the original field flags, status owner, initializer and complete
	// read inventory. A stale projection cannot certify different declarations.
	packet, known := nativeMemberAssertionProofMode(c.obj, c.obj.GetClassName(), c.Work, true)
	if !known || packet == nil || !reflect.DeepEqual(packet, state.packet) {
		return
	}
	for i := range c.report.Members {
		row := &c.report.Members[i]
		if row.Owner != c.obj.GetClassName() || row.State != "unsupported" {
			continue
		}
		if row.Kind == "field" && row.Name == nativeAssertionField && row.Descriptor == "Z" {
			row.State, row.Evidence = "regenerated", "complete original assertion-status field/initializer/read protocol regenerated by published typed assertions"
		}
		if row.Kind == "method" && row.Name == "<clinit>" && row.Descriptor == "()V" && packet.pureInitializer {
			row.State, row.Evidence = "regenerated", "entire original initializer is the assertion-status protocol regenerated by published typed assertions"
		}
	}
}
