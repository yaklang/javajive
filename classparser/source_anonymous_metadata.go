type sourceAnonymousClassMetadataPlan struct {
	owner, classKey string
	originalHash    [32]byte
}

func sourceAnonymousMetadataPlansEqual(left, right *sourceAnonymousClassMetadataPlan) bool {
	if left == nil || right == nil {
		return left == right
	}
	return *left == *right
}

// The old static anonymous source shape is independently recognized by the
// native compiler proof. Only an explicit artifact can additionally owe the
// final class bit and static anonymous InnerClasses rows to that compiler.
// Capture stores are regenerated by javac; none may commute across SUPER.
func (c *ClassObjectDumper) artifactStaticAnonymousConstructor(object *ClassObject, owner, method, assertionRoot string, members *nativeMemberFamily, forest *nativeAnonymousForest, metadata callbinding.Provider, access map[string]*nativeConstructorAccessBridge) *nativeAnonymousClass {
	if !c.artifactLambdaMetadataAllowed() || c.obj.GetClassName() != owner || object == nil || object.MajorVersion != 52 || object.MinorVersion != 0 || object.AccessFlags != 0x0030 || !nativeAnonymousSelfAccessFlags(object, 8, c.Work) {
		return nil
	}
	static, known := nativeAnonymousOriginalContext(c.obj, object, method, c.Work)
	if !known || !static {
		return nil
	}
	child := c.nativeJavac8AnonymousConstructor(object, owner, method, assertionRoot, members, forest, metadata, access)
	if !sourceAnonymousStaticConstructorDomain(child, metadata, c.Work) {
		return nil
	}
	child.artifactStaticMetadata = true
	if c.artifactAnonymousClassPlan(child) == nil {
		return nil
	}
	return child
}

// Checked SUPER/initializer effects need a separate Exceptions-attribute
// obligation. This domain has only hidden captures and an implicit no-arg
// parent with a complete empty checked-exception declaration.
func sourceAnonymousStaticConstructorDomain(child *nativeAnonymousClass, metadata callbinding.Provider, work *workbudget.Budget) bool {
	if child == nil || child.object == nil || child.enclosingField != "" || child.unusedEnclosing || child.sharedParameterRoles || len(child.superParams) != 0 || child.superDescriptor != "()V" || len(child.initializers) != 0 || child.expressionInitializer != nil {
		return false
	}
	exceptions, known := exactInvocationExceptions(metadata, child.object.GetSupperClassName(), "<init>", "()V")
	return known && len(exceptions) == 0 && nativeProofWork(work, 1)
}

func (c *ClassObjectDumper) artifactAnonymousClassPlan(child *nativeAnonymousClass) *sourceAnonymousClassMetadataPlan {
	if child == nil || !child.artifactStaticMetadata || !c.artifactLambdaMetadataAllowed() || child.object == nil || child.object.MajorVersion != 52 || child.object.MinorVersion != 0 || child.object.AccessFlags != 0x0030 || !nativeAnonymousSelfAccessFlags(child.object, 8, c.Work) || !sourceAnonymousStaticConstructorDomain(child, c.buildInvocationMetadata(), c.Work) {
		return nil
	}
	static, known := nativeAnonymousOriginalContext(c.obj, child.object, child.method, c.Work)
	if !known || !static {
		return nil
	}
	raw, known := c.options.sourceLambdaMetadata.original(child.object, c.Work)
	key, keyed := sourceParameterClassKey(child.object, child.object.ThisClass)
	if !known || !keyed {
		return nil
	}
	return &sourceAnonymousClassMetadataPlan{owner: child.object.GetClassName(), classKey: key, originalHash: sha256.Sum256(raw)}
}

func (a *sourceLambdaMetadataAuthority) restoreAnonymousClassMetadata(original, compiled []byte, work *workbudget.Budget) ([]byte, error) {
	a.mu.Lock()
	if len(a.anonymous) == 0 {
		a.mu.Unlock()
		return compiled, nil
	}
	if len(a.anonymous) > 4096 || !nativeProofWork(work, int64(len(a.anonymous))+1) || work.CheckAlloc(int64(len(a.anonymous))*160) != nil {
		a.mu.Unlock()
		return nil, sourceLambdaMetadataFailure(work, "anonymous metadata ledger budget")
	}
	plans := make(map[string]*sourceAnonymousClassMetadataPlan, len(a.anonymous))
	for _, plan := range a.anonymous {
		if plan == nil || plans[plan.classKey] != nil {
			a.mu.Unlock()
			return nil, sourceLambdaMetadataFailure(work, "ambiguous anonymous metadata ledger")
		}
		plans[plan.classKey] = plan
	}
	a.mu.Unlock()
	return restoreSourceAnonymousClassMetadata(original, compiled, plans, work)
}

type sourceAnonymousInnerRow struct {
	outer, name string
	flags       uint16
	ordinal     int
	anonymous   bool
}

func sourceAnonymousInnerRows(object *ClassObject, work *workbudget.Budget) (map[string]sourceAnonymousInnerRow, error) {
	rows := map[string]sourceAnonymousInnerRow{}
	seen := false
	text := int64(0)
	for _, attribute := range object.Attributes {
		table, isTable := attribute.(*InnerClassesAttribute)
		if !isTable {
			continue
		}
		if table == nil || seen || len(table.Classes) > 65535 || !nativeProofWork(work, int64(len(table.Classes))+1) || work.CheckAlloc(int64(len(table.Classes))*128) != nil {
			return nil, sourceLambdaMetadataFailure(work, "invalid anonymous declaration table")
		}
		seen = true
		for i, row := range table.Classes {
			if row == nil {
				return nil, sourceLambdaMetadataFailure(work, "nil anonymous declaration row")
			}
			inner, ik := sourceParameterClassKey(object, row.InnerClassInfoIndex)
			outer, name, ok := "", "", true
			if row.OuterClassInfoIndex != 0 {
				outer, ok = sourceParameterClassKey(object, row.OuterClassInfoIndex)
			}
			if ok && row.InnerNameIndex != 0 {
				name, ok = sourceParameterUTF8Key(object, row.InnerNameIndex)
			}
			cost := int64(len(inner) + len(outer) + len(name) + 1)
			_, duplicate := rows[inner]
			if !ik || !ok || inner == "" || duplicate || cost > (128<<20)-text || !nativeProofWork(work, cost) || work.CheckAlloc(text+cost+int64(len(rows)+1)*128) != nil {
				return nil, sourceLambdaMetadataFailure(work, "ambiguous anonymous declaration identity")
			}
			text += cost
			rows[inner] = sourceAnonymousInnerRow{outer, name, row.InnerClassAccessFlags, i, row.OuterClassInfoIndex == 0 && row.InnerNameIndex == 0}
		}
	}
	return rows, nil
}

// Cache physical CP aliases before comparing every interface position. A large
// repeated interface list must not repeatedly encode a large shared name.
func sourceAnonymousClassHeadClosed(left, right *ClassObject, work *workbudget.Budget) bool {
	if len(left.Interfaces) != len(right.Interfaces) || !nativeProofWork(work, int64(len(left.Interfaces))+2) {
		return false
	}
	text := int64(0)
	read := func(object *ClassObject, cache map[uint16]string, index uint16) (string, bool) {
		if index == 0 {
			return "", true
		}
		if key, found := cache[index]; found {
			return key, true
		}
		key, known := sourceParameterClassKey(object, index)
		cost := int64(len(key)) + 1
		if !known || key == "" || cost > (128<<20)-text || !nativeProofWork(work, cost) || work.CheckAlloc(text+cost+int64(len(cache)+1)*64) != nil {
			return "", false
		}
		text += cost
		cache[index] = key
		return key, true
	}
	a, b := map[uint16]string{}, map[uint16]string{}
	pair := func(x, y uint16) bool {
		first, fk := read(left, a, x)
		second, sk := read(right, b, y)
		return fk && sk && first == second
	}
	if !pair(left.ThisClass, right.ThisClass) || !pair(left.SuperClass, right.SuperClass) {
		return false
	}
	for i, entry := range left.Interfaces {
		if !pair(entry, right.Interfaces[i]) {
			return false
		}
	}
	return true
}

// Reconstruct only the independently enrolled compiler differences. Existing
// CP entries, all Code payloads and unrelated metadata bytes stay untouched.
// Each physical source namespace owns a separate completed-plan ledger.
func restoreSourceAnonymousClassMetadata(original, compiled []byte, plans map[string]*sourceAnonymousClassMetadataPlan, work *workbudget.Budget) ([]byte, error) {
	fail := func(reason string) ([]byte, error) {
		if err := work.Check(); err != nil {
			return nil, err
		}
		return nil, fmt.Errorf("anonymous metadata: %s", reason)
	}
	if len(original) > 32<<20 || len(compiled) > 32<<20 || len(plans) > 4096 || !nativeProofWork(work, int64(len(original)+len(compiled))+1) {
		return fail("class or ledger budget")
	}
	want, err := ParseWithBudget(original, work)
	if err != nil {
		return nil, err
	}
	reader, err := NewClassReaderWithBudget(compiled, work)
	if err != nil {
		return nil, err
	}
	layout := &compiledMetadataLayout{methods: map[*MemberInfo]compiledMetadataSpan{}}
	got, err := parseWithMetadataLayout(reader, nil, layout)
	if err != nil {
		return nil, err
	}
	key, keyed := sourceParameterClassKey(want, want.ThisClass)
	if !keyed {
		return fail("class identity unavailable")
	}
	var edits []compiledMetadataEdit
	if plan := plans[key]; plan != nil {
		if plan.classKey != key || plan.owner != want.GetClassName() || sha256.Sum256(original) != plan.originalHash || want.MajorVersion != 52 || got.MajorVersion != 52 || want.MinorVersion != 0 || got.MinorVersion != 0 || want.AccessFlags != 0x0030 || got.AccessFlags != 0x0020 && got.AccessFlags != 0x0030 || !nativeAnonymousSelfAccessFlags(want, 8, work) {
			return fail("missing or stale static anonymous proof")
		}
		if got.AccessFlags != want.AccessFlags {
			edits = append(edits, compiledMetadataEdit{compiledMetadataSpan{layout.poolEnd, layout.poolEnd + 2}, []byte{0, 0x30}})
		}
	} else if want.AccessFlags != got.AccessFlags {
		return fail("unrelated class flags changed")
	}
	if !sourceAnonymousClassHeadClosed(want, got, work) {
		return fail("class, parent or interface identity changed")
	}
	wanted, err := sourceAnonymousInnerRows(want, work)
	if err != nil {
		return nil, err
	}
	actual, err := sourceAnonymousInnerRows(got, work)
	if err != nil {
		return nil, err
	}
	for inner, row := range wanted {
		if plans[inner] == nil {
			continue
		}
		rebuilt, exists := actual[inner]
		if !exists || !row.anonymous || row.flags != 8 || !rebuilt.anonymous || rebuilt.flags != 0 && rebuilt.flags != 8 {
			return fail("anonymous ownership or static row changed")
		}
		if rebuilt.flags == row.flags {
			continue
		}
		span := layout.innerClassSpan
		pos := span.start + 6 + 2 + 8*rebuilt.ordinal + 6
		if layout.innerClasses == nil || span.end-span.start != 8+8*len(layout.innerClasses.Classes) || pos < span.start || pos+2 > span.end || span.end > len(compiled) || binary.BigEndian.Uint16(compiled[pos:]) != rebuilt.flags {
			return fail("compiled row span unavailable")
		}
		edits = append(edits, compiledMetadataEdit{compiledMetadataSpan{pos, pos + 2}, []byte{0, 8}})
	}
	for inner := range actual {
		if plans[inner] != nil {
			if _, exists := wanted[inner]; !exists {
				return fail("unowned generated anonymous row")
			}
		}
	}
	return applyCompiledMetadataEdits(compiled, edits, work)
}
