package javaclassparser

import (
	"strings"

	"github.com/yaklang/javajive/classparser/decompiler/core/values/types"
)

// descriptorProjectionWithoutEnclosingMethod is a source projection, not an
// ownership or generic-binding certificate. Some obfuscators retain Signature
// attributes that mention a local class's enclosing method formals, but remove
// EnclosingMethod itself. Declaring those names as unbounded formals invents
// Object erasures and can change physical method descriptors. Instead, omit
// the unbound generic metadata and render the original executable descriptors.
// Code bytes, exception tables, access flags, names and descriptors are unchanged.
// A present (even malformed) EnclosingMethod must still pass the existing proof.
// method_index 0 names no enclosing method. RetainUnprovedSource may then omit the
// unbound Signature the same way a missing attribute does. It does not declare <T>.
func (c *ClassObjectDumper) descriptorProjectionWithoutEnclosingMethod() *ClassObject {
	if c == nil || c.obj == nil || c.foldSiblingResolver == nil || c.nativeCaptureFields != nil || c.nativeMemberCurrent != nil || c.nativeAnonymousRoot != nil {
		return nil
	}
	obj := c.obj
	if obj.MajorVersion < 49 || obj.AccessFlags&0x4000 != 0 {
		return nil
	}
	rows := 0
	for _, a := range obj.Attributes {
		if raw, ok := a.(*UnparsedAttribute); ok && raw != nil && raw.Name == "EnclosingMethod" {
			if !c.options.RetainUnprovedSource || len(raw.Info) != 4 || raw.Info[2] != 0 || raw.Info[3] != 0 {
				return nil
			}
			continue
		}
		if table, ok := a.(*InnerClassesAttribute); ok {
			if table == nil {
				return nil
			}
			for _, row := range table.Classes {
				if row == nil {
					return nil
				}
				if row.InnerClassInfoIndex == obj.ThisClass {
					if row.OuterClassInfoIndex != 0 {
						return nil
					}
					rows++
				}
			}
		}
	}
	if rows != 1 {
		return nil
	}
	signature, valid := nativeMethodLocalOriginalSignature(obj, obj.Attributes, c.Work)
	if !valid || len(types.ClassFormalTypeParamNames(signature)) != 0 || len(flattenedFreeTypeVariables(obj, signature, true)) == 0 {
		return nil
	}
	projected := *obj
	projected.Attributes = withoutGenericProjectionAttributes(obj.Attributes)
	projected.Fields = make([]*MemberInfo, len(obj.Fields))
	projected.Methods = make([]*MemberInfo, len(obj.Methods))
	for i, field := range obj.Fields {
		if field == nil {
			return nil
		}
		copy := *field
		copy.Attributes = withoutGenericProjectionAttributes(field.Attributes)
		projected.Fields[i] = &copy
	}
	for i, method := range obj.Methods {
		if method == nil {
			return nil
		}
		copy := *method
		copy.Attributes = withoutGenericProjectionAttributes(method.Attributes)
		projected.Methods[i] = &copy
	}
	return &projected
}

// Raw supertypes no longer cause javac to regenerate parameter-erasing bridges
// (forward(Object) -> forward(Integer)). Retain those original method bodies.
// Return-only covariant bridges still have an override-equivalent source
// signature and are regenerated by javac; do not emit a duplicate declaration.
func (c *ClassObjectDumper) keepDescriptorProjectionBridge(method *MemberInfo) bool {
	if !c.descriptorSourceProjection || method == nil {
		return false
	}
	name, nk := sourceBridgeUTF8(c.obj, method.NameIndex)
	desc, dk := sourceBridgeUTF8(c.obj, method.DescriptorIndex)
	end := strings.IndexByte(desc, ')')
	if !nk || !dk || end < 0 {
		return false
	}
	for _, other := range c.obj.Methods {
		if other == nil || other == method || isBridgeMethod(other.AccessFlags) {
			continue
		}
		n, _ := sourceBridgeUTF8(c.obj, other.NameIndex)
		d, _ := sourceBridgeUTF8(c.obj, other.DescriptorIndex)
		e := strings.IndexByte(d, ')')
		if n == name && e >= 0 && d[:e+1] == desc[:end+1] {
			return false
		}
	}
	return true
}

func withoutGenericProjectionAttributes(attrs []AttributeInfo) []AttributeInfo {
	result := make([]AttributeInfo, 0, len(attrs))
	for _, attr := range attrs {
		switch a := attr.(type) {
		case *SignatureAttribute:
			continue
		case *UnparsedAttribute:
			if a != nil && a.Name == "LocalVariableTypeTable" {
				continue
			}
		case *CodeAttribute:
			if a != nil {
				copy := *a
				copy.Attributes = withoutGenericProjectionAttributes(a.Attributes)
				attr = &copy
			}
		}
		result = append(result, attr)
	}
	return result
}
