package javaclassparser

import (
	"github.com/yaklang/javajive/classparser/decompiler/core"
	"github.com/yaklang/javajive/classparser/decompiler/core/callbinding"
	"github.com/yaklang/javajive/classparser/decompiler/core/values"
)

// Result conversion is after the selected invocation. It cannot grant argument
// binding, eager capture checks or synthetic declaration ownership. Match every
// original executable tail instruction; never treat a well-typed arbitrary
// conversion body as a compiler-owned method reference.
func (c *ClassObjectDumper) originalVarargsResultConversion(code *CodeAttribute, ops []*core.OpCode, index int, from, to string) (int, bool) {
	if c == nil || code == nil || from == "" || to == "" || index < 0 || index >= len(ops) || !nativeProofWork(c.Work, 1) {
		return index, false
	}
	consume := func(opcode int) bool {
		if index >= len(ops) || ops[index].Instr.OpCode != opcode || !constructorEffectOriginalOperandFree(code, ops[index]) {
			return false
		}
		index++
		return true
	}
	if from == to {
		return index, true
	}
	if to == "V" {
		op := core.OP_POP
		if from == "J" || from == "D" {
			op = core.OP_POP2
		}
		if from == "V" || !consume(op) {
			return index, false
		}
		return index, true
	}
	if from == "V" {
		return index, false
	}
	if callbinding.Reference(from) && callbinding.Reference(to) {
		return index, c.varargsResultReferenceWidening(from, to)
	}
	if opcode, known := varargsResultPrimitiveWidening(from, to); known {
		if opcode < 0 {
			return index, true
		}
		if !consume(opcode) {
			return index, false
		}
		return index, true
	}
	// These are the language's boxing carriers. They constrain the actual CP
	// call regenerated by javac, not an assumption that valueOf is pure. Its
	// allocation/class-initialization/failure remains after the target call.
	wrappers := map[string]string{"Z": "java/lang/Boolean", "B": "java/lang/Byte", "C": "java/lang/Character", "S": "java/lang/Short", "I": "java/lang/Integer", "J": "java/lang/Long", "F": "java/lang/Float", "D": "java/lang/Double"}
	owner := wrappers[from]
	if owner == "" || !callbinding.Reference(to) {
		return index, false
	}
	boxed := "L" + owner + ";"
	if !c.varargsResultReferenceWidening(boxed, to) || index >= len(ops) {
		return index, false
	}
	member := constructorMotionMember(c.obj, ops[index], core.OP_INVOKESTATIC)
	// Boxing calls are class Methodrefs. An InterfaceMethodref to a known
	// wrapper would fail linkage and cannot be replaced by compiler boxing.
	if member != nil {
		ref, known := c.obj.ConstantPool[core.Convert2bytesToInt(ops[index].Data[:2])-1].(*ConstantMethodrefInfo)
		if !known || ref == nil {
			return index, false
		}
	}
	if member == nil || *member != (values.JavaClassMember{Name: owner, Member: "valueOf", Description: "(" + from + ")" + boxed}) || !c.varargsOriginalBoxingDeclaration(owner, from, boxed) {
		return index, false
	}
	return index + 1, true
}

// JLS primitive widening maps to this exact JVM conversion (or no instruction
// for byte/short/char to int). Narrowing and widening-then-boxing are not Java
// method-reference result assignment conversions and do not enter this grammar.
func varargsResultPrimitiveWidening(from, to string) (int, bool) {
	if from == to && len(from) == 1 {
		return -1, true
	}
	// A common JVM operand category does not determine javac's tail.
	// Its legal byte-to-short widening normalizes the original result
	// with I2S. Require that exact emitted instruction; this does not
	// permit int/char/other narrowing as reference-result adaptation.
	if from == "B" && to == "S" {
		return core.OP_I2S, true
	}
	source := from
	if from == "B" || from == "S" || from == "C" {
		if to == "I" {
			return -1, true
		}
		source = "I"
	}
	opcode, known := map[[2]string]int{{"I", "J"}: core.OP_I2L, {"I", "F"}: core.OP_I2F, {"I", "D"}: core.OP_I2D, {"J", "F"}: core.OP_L2F, {"J", "D"}: core.OP_L2D, {"F", "D"}: core.OP_F2D}[[2]string{source, to}]
	return opcode, known
}

func (c *ClassObjectDumper) varargsResultMetadata() callbinding.Provider {
	provider := c.buildInvocationMetadata()
	remaining := 1024
	return func(n string) (callbinding.Class, bool) {
		remaining--
		if remaining < 0 || !nativeProofWork(c.Work, 1) {
			return callbinding.Class{}, false
		}
		cl, known := provider(n)
		if !known || cl.Name != n || !cl.ParentsComplete || len(cl.Parents) > 64 || !nativeProofWork(c.Work, int64(len(cl.Parents))+1) {
			return callbinding.Class{}, false
		}
		return cl, true
	}
}
func (c *ClassObjectDumper) varargsResultReferenceWidening(from, to string) bool {
	if !callbinding.Reference(from) || !callbinding.Reference(to) {
		return false
	}
	return callbinding.Assignable(from, to, c.varargsResultMetadata())
}
func (c *ClassObjectDumper) varargsOriginalBoxingDeclaration(owner, primitive, boxed string) bool {
	cl, known := c.varargsResultMetadata()(owner)
	if !known || !cl.Public || !cl.Final || cl.IsInterface || !cl.MembersComplete || len(cl.Methods) > 4096 {
		return false
	}
	matches := 0
	for _, m := range cl.Methods {
		if !nativeProofWork(c.Work, 1) {
			return false
		}
		if m.Name == "valueOf" && m.Desc == "("+primitive+")"+boxed {
			if !m.Public || !m.Static || m.Varargs || m.Generic || m.Bridge || !m.ExceptionsKnown || len(m.Exceptions) != 0 {
				return false
			}
			matches++
		}
	}
	return matches == 1
}
