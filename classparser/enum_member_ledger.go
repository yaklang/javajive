package javaclassparser

import "github.com/yaklang/javajive/classparser/decompiler/core"

// Called only after final source publication proofs. The ordinary ledger
// cannot find declarations which Java's enum syntax regenerates. Account for
// those members from the complete original enum protocol, rather than names,
// flags alone or an assertion that compilable source must be equivalent.
func (c *ClassObjectDumper) recordEnumRegeneratedMembers(source string, methods []*dumpedMethods) {
	if c.report == nil || c.obj == nil || c.enumParameterMetadataUnsupported || c.options.SourceCompiler.effective() != ModernJavac || c.obj.MajorVersion != 52 || core.EffectiveTargetSource(c.options.TargetSourceVersion, c.obj.MajorVersion) != 8 {
		return
	}
	proof := nativeEnumDeclarationSynthesis(c.obj, nil, c.Work, false, false)
	if proof == nil {
		return
	}
	type key struct{ kind, name, descriptor string }
	regenerated := map[key]string{}
	helper := false
	for _, method := range c.obj.Methods {
		name, named := sourceBridgeUTF8(c.obj, method.NameIndex)
		descriptor, typed := sourceBridgeUTF8(c.obj, method.DescriptorIndex)
		generated, err := nativeEnumRegeneratedMethod(c.obj, method, name, descriptor, c.Work)
		if !named || !typed || err != nil {
			return
		}
		if generated {
			helper = helper || method.AccessFlags == 0x100a
			regenerated[key{"method", name, descriptor}] = "original enum factory/array Code and constructor/constant protocol regenerated by enum syntax"
		}
	}
	// This compiler profile emits the private array helper. An original
	// compiler with an inline array has a different synthetic method inventory.
	if !helper {
		return
	}
	name, named := sourceBridgeUTF8(c.obj, proof.valuesField.NameIndex)
	descriptor, typed := sourceBridgeUTF8(c.obj, proof.valuesField.DescriptorIndex)
	if !named || !typed {
		return
	}
	regenerated[key{"field", name, descriptor}] = "original enum backing array and constant initialization protocol regenerated by enum syntax"
	for _, parent := range methods {
		if parent != nil && parent.enumLambdaInitializer != nil {
			if _, _, closed := c.enumLambdaInitializerSourceSpan(source, parent); !closed {
				return
			}
			regenerated[key{"method", "<clinit>", "()V"}] = "original enum initializer factories consumed by the actual final constant arguments"
		}
	}
	for i := range c.report.Members {
		row := &c.report.Members[i]
		if row.Owner != c.obj.GetClassName() || row.State == "stub" || row.State == "dropped" {
			continue
		}
		if evidence := regenerated[key{row.Kind, row.Name, row.Descriptor}]; evidence != "" {
			row.State, row.Evidence = "regenerated", evidence
		}
	}
}
